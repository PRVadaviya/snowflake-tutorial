/* STANDARD VIEW */
-- STANDARD VIEW IS KIND OF A VIRTUAL TABLE WHOSE RESULTS ARE GENERATED BY RUNNING QUERY

-- LET'S CREATE VIEW 'IT_EMPLOYEE' THAT ONLY INCLUDES THE IT EMPLOYEE
CREATE OR REPLACE VIEW IT_EMPLOYEES AS 
SELECT ID, NAME, SALARY 
FROM EMPLOYEES
WHERE DEPARTMENT = 'IT';

SELECT * FROM IT_EMPLOYEES;



/* SECURE VIEW */

-- LET'S CREATE SECURE VIEW 'HR_EMPLOYEE' THAT ONLY INCLUDES THE HR EMPLOYEE
CREATE OR REPLACE SECURE VIEW HR_EMPLOYEES AS 
SELECT ID, NAME, SALARY 
FROM EMPLOYEES
WHERE DEPARTMENT = 'HR';

SELECT * FROM HR_EMPLOYEES;


/* MATERIALIZED VIEW */

-- CREATE VIEW THAT AGGREGATES THE SALARIES BY DEPARTMENT

/* STANDARD VIEW 
   FLOW : FIRST SCAN THE TABLE , BRING THE DATA DO THE AGGREGATION AND GIVE IT TO THE RESULT  */
CREATE OR REPLACE VIEW EMPLOYEE_SALARIES AS 
SELECT 
    DEPARTMENT,
    SUM(SALARY) AS TOTAL_SALARY
FROM EMPLOYEES
GROUP BY DEPARTMENT;

SELECT * FROM EMPLOYEE_SALARIES;

/* MATERIALIZED VIEW 
FLOW : SNOWFLAKE AUTOMATICALLY DOES THE AGGREGATION ON THE BACKEND, STORE THE DATA IN CACHE, BRING THE DATA FROM THERE.
USECASE : WHEN COMPLICATED AGGREGATION EXISTS IN QUERY AND YOU ARE RUNNING EVERY TIME THAT TIME USE M. VIEW */

CREATE OR REPLACE MATERIALIZED VIEW MATERIALIZED_EMPLOYEE_SALARIES AS 
SELECT 
    DEPARTMENT,
    SUM(SALARY) AS TOTAL_SALARY
FROM EMPLOYEES
GROUP BY DEPARTMENT;

SELECT * FROM MATERIALIZED_EMPLOYEE_SALARIES;
